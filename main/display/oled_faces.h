inline const uint8_t* GetOledFaceBitmap(const char* emotion) {
    if (!emotion || emotion[0] == '\0') return oled_face_neutral;

    if (strcmp(emotion, "happy") == 0 || strcmp(emotion, "laughing") == 0 || strcmp(emotion, "funny") == 0) {
        return oled_face_happy;
    } else if (strcmp(emotion, "sad") == 0 || strcmp(emotion, "crying") == 0) {
        return oled_face_sad;
    } else if (strcmp(emotion, "angry") == 0) {
        return oled_face_angry;
    } else if (strcmp(emotion, "loved") == 0 || strcmp(emotion, "love") == 0) {
        return oled_face_loved;
    } else if (strcmp(emotion, "excited") == 0) {
        return oled_face_excited;
    } else if (strcmp(emotion, "tired") == 0) {
        return oled_face_tired;
    } else if (strcmp(emotion, "confused") == 0 || strcmp(emotion, "thinking") == 0) {
        return oled_face_confused;
    } else if (strcmp(emotion, "shy") == 0) {
        return oled_face_shy;
    } else if (strcmp(emotion, "surprised") == 0 || strcmp(emotion, "listening") == 0) {
        return oled_face_surprised;
    } else if (strcmp(emotion, "disgusted") == 0) {
        return oled_face_disgusted;
    } else if (strcmp(emotion, "sleepy") == 0) {
        return oled_face_sleepy;
    } else if (strcmp(emotion, "broken") == 0) {
        return oled_face_broken;
    } else if (strcmp(emotion, "cool") == 0) {
        return oled_face_cool;
    } else if (strcmp(emotion, "worried") == 0) {
        return oled_face_worried;
    } else if (strcmp(emotion, "playful") == 0 || strcmp(emotion, "speaking") == 0) {
        return oled_face_playful;
    } else if (strcmp(emotion, "teary") == 0) {
        return oled_face_teary;
    }

    return oled_face_neutral;
}

